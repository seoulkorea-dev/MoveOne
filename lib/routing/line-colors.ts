export function subwayColor(lineName: string | null | undefined): string {
  if (!lineName) return MODE_COLOR.subway;
  for (const [needle, color] of SUBWAY_COLORS) {
    if (lineName.includes(needle)) return color;
  }
  return MODE_COLOR.subway;
}

/**
 * 버스 노선색. TOPIS routeType 기준입니다.
 *
 * 2026-09-16 실측으로 확인한 값: 3(604번) · 7(1400인천) · 8(9000-1광주).
 * 나머지는 TOPIS 문서 체계를 따릅니다. 모르는 값은 기본 버스색입니다.
 */
export function busColor(routeType: number | null | undefined): string {
  switch (routeType) {
    case 1:
      return "#0068B7"; // 공항
    case 2:
      return "#5BB025"; // 마을
    case 3:
      return "#0068B7"; // 간선
    case 4:
      return "#5BB025"; // 지선
    case 5:
      return "#F99D1C"; // 순환
    case 6:
      return "#E7352C"; // 광역
    case 7:
      return "#E7352C"; // 인천 (광역 계열이 많습니다)
    case 8:
      return "#E7352C"; // 경기
    default:
      return MODE_COLOR.bus;
  }
}

